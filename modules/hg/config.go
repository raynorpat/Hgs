// Package hg is the only way the application starts Mercurial. It runs the
// configured executable with an application-owned configuration, a stripped
// environment, a bounded number of concurrent processes, and process-tree
// cleanup on every platform.
package hg

import "time"

// Config holds the operator-tunable Mercurial settings.
type Config struct {
	// Executable is the absolute path of the hg executable.
	Executable string
	// ConfigPath is the absolute path of the managed hgrc, used as the sole
	// HGRCPATH entry. The runner rewrites it at startup.
	ConfigPath string
	// MaxProcesses bounds concurrently running hg processes started by the
	// runner. Zero means DefaultMaxProcesses.
	MaxProcesses int
	// SessionTimeout is the ceiling for any process started with Start.
	// Zero means DefaultSessionTimeout.
	SessionTimeout time.Duration
}

const (
	DefaultMaxProcesses   = 8
	DefaultSessionTimeout = 30 * time.Minute

	// StartupTimeout bounds each startup probe and backend readiness wait.
	StartupTimeout = 10 * time.Second
	// BrowserCommandTimeout bounds one web-browsing command; callers apply it.
	BrowserCommandTimeout = 30 * time.Second
	// TransferIdleTimeout ends a started process with no stdio activity.
	TransferIdleTimeout = 120 * time.Second
	// QueueTimeout bounds the wait for a free process slot.
	QueueTimeout = 5 * time.Second
	// ShutdownTimeout bounds a graceful Stop before the tree is killed.
	ShutdownTimeout = 30 * time.Second

	MaxRenderedFileBytes = 1 << 20
	MaxDiffBytes         = 2 << 20
	MaxDiffLines         = 10000
	// MaxCommandOutput bounds Run output: the largest browser payload.
	MaxCommandOutput = MaxDiffBytes

	maxStderrBytes = 64 << 10
)

// managedConfig is the whole of Mercurial's configuration apart from the
// application-written repository hgrc: no user, system or extension config.
const managedConfig = `# Generated by Gogs at startup; local edits are overwritten.
[ui]
interactive = false
paginate = false
color = never
`
